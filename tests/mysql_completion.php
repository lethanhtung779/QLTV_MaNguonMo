<?php
declare(strict_types=1);
require __DIR__.'/test_database_guard.php';
require dirname(__DIR__).'/bootstrap/app.php';
use Library\Core\Database;
use Library\Repositories\BookRepository;
use Library\Repositories\CopyRepository;
use Library\Repositories\MetadataRepository;
use Library\Repositories\ReaderRepository;
use Library\Services\LoanService;
$db=Database::connection(); $checks=0;
$assert=function($ok,$label) use (&$checks) { if (!$ok) throw new RuntimeException('FAIL: '.$label); $checks++; echo 'PASS: '.$label.PHP_EOL; };
$reject=function(callable $call,$label) use($assert) { try {$call();} catch (RuntimeException $e) { if ($e instanceof PDOException) throw $e; $assert(true,$label); return;} $assert(false,$label); };
$actor=(int)$db->query('SELECT id FROM users WHERE role="admin" AND is_active=1 LIMIT 1')->fetchColumn();
$tag='QAF-'.strtoupper(bin2hex(random_bytes(4))); $books=new BookRepository($db); $copies=new CopyRepository($db);
$data=['book_code'=>$tag,'title'=>'Kiểm thử hoàn thiện','author'=>$tag.' Author','isbn'=>null,'category_id'=>null,'publisher'=>$tag.' Publisher','publication_year'=>2026,'description'=>null,'total_copies'=>2,'cover_url'=>null];
$book=$books->create($data);
$reader=(new ReaderRepository($db))->create(['user_id'=>null,'card_number'=>$tag,'full_name'=>$tag,'phone'=>null,'email'=>null,'address'=>null,'expires_on'=>date('Y-m-d',strtotime('+1 year'))]);
$list=$copies->all($book); $cp=(int)$list[0]['id'];
$copyData=['copy_code'=>$list[0]['copy_code'],'barcode'=>$tag.'-BC','shelf_location'=>'A-02','item_condition'=>'good','status'=>'available'];
$copies->save($book,$cp,$copyData,$actor);
$assert($copies->all($book)[0]['shelf_location']==='A-02','Shelf location and barcode persist');
$copyData['copy_code']=$tag.'-EXTRA';
try { $copies->save($book,0,$copyData,$actor); $assert(false,'Duplicate barcode rejected'); }
catch (PDOException $e) { $assert($e->getCode()==='23000' && count($copies->all($book))===2,'Duplicate barcode rejected without partial insert'); }
$copyData['barcode']=null; $new=$copies->save($book,0,$copyData,$actor);
$assert((int)$books->find($book)['total_copies']===3,'Adding a physical copy updates inventory');
$copyData['copy_code']=$list[0]['copy_code']; $copyData['status']='damaged'; $copyData['item_condition']='damaged';
$copies->save($book,$cp,$copyData,$actor); $service=new LoanService($db,5000);
$reject(fn()=>$service->checkout($reader,[$cp],$actor,date('Y-m-d'),date('Y-m-d',strtotime('+1 day'))),'Damaged copy cannot be borrowed');
$assert((int)$books->find($book)['available_copies']===2,'Damaged copy excluded from available inventory');
$copyData['status']='available'; $copyData['item_condition']='good'; $copies->save($book,$cp,$copyData,$actor);
$code=$service->checkout($reader,[$cp,$new],$actor,date('Y-m-d'),date('Y-m-d',strtotime('+1 day')));
$loan=(int)$db->query('SELECT id FROM loans WHERE loan_code='.$db->quote($code))->fetchColumn();
$items=$db->query('SELECT id FROM loan_items WHERE loan_id='.$loan.' ORDER BY id')->fetchAll(PDO::FETCH_COLUMN);
$reject(fn()=>$copies->save($book,$cp,$copyData,$actor),'Manual copy update cannot bypass an active loan');
$assert($books->deleteConflicts($book),'Active item blocks archival');
$service->returnBook((int)$items[0],$actor);
$reject(fn()=>$service->returnBook((int)$items[0],$actor),'Duplicate return rejected');
$assert($db->query('SELECT returned_at FROM loans WHERE id='.$loan)->fetchColumn()===null,'Partial return keeps loan open');
$due=$service->renew((int)$items[1],$actor);
$assert($due>date('Y-m-d',strtotime('+1 day')),'Remaining item can be renewed');
$service->returnBook((int)$items[1],$actor);
$assert(!$books->deleteConflicts($book),'Closed history does not block archival');
$books->delete($book);
$assert((int)$db->query('SELECT COUNT(*) FROM loan_items WHERE loan_id='.$loan)->fetchColumn()===2,'Archival preserves loan history');
$author=(int)$db->query('SELECT id FROM authors WHERE name='.$db->quote($tag.' Author'))->fetchColumn();
$meta=new MetadataRepository($db,'authors'); $meta->save($author,$tag.' Renamed',$actor);
$assert($db->query('SELECT author FROM books WHERE id='.$book)->fetchColumn()===$tag.' Renamed','Author rename synchronizes legacy book metadata');
$reject(fn()=>$meta->delete($author,$actor),'Referenced author deletion rejected');
$unused=$meta->save(0,$tag.' Unused',$actor); $meta->delete($unused,$actor);
$assert((int)$db->query('SELECT COUNT(*) FROM authors WHERE id='.$unused)->fetchColumn()===0,'Unused author CRUD works');
$assert(count($books->search('',0,'',2,0,'title'))===2,'Pagination bounds database result size');
$assert($books->countSearch('Nha gia kim')>0,'Vietnamese search without accents uses database collation');
$assert((int)$db->query('SELECT COUNT(*) FROM book_copies c WHERE (c.status="on_loan") <> EXISTS(SELECT 1 FROM loan_items li WHERE li.book_copy_id=c.id AND li.returned_at IS NULL)')->fetchColumn()===0,'All inventory agrees with active loan items');
$publisher=(int)$db->query('SELECT publisher_id FROM books WHERE id='.$book)->fetchColumn();
$pub=new MetadataRepository($db,'publishers');$pub->save($publisher,$tag.' New Publisher',$actor);
$assert($db->query('SELECT publisher FROM books WHERE id='.$book)->fetchColumn()===$tag.' New Publisher','Publisher rename synchronizes books');
$reject(fn()=>$pub->delete($publisher,$actor),'Referenced publisher deletion rejected');
$unused=$pub->save(0,$tag.' Unused Publisher',$actor);$pub->delete($unused,$actor);
$assert((int)$db->query('SELECT COUNT(*) FROM publishers WHERE id='.$unused)->fetchColumn()===0,'Unused publisher CRUD works');
$summary=(new \Library\Repositories\LoanRepository($db))->summary();
$assert((int)$summary['active_loan_count']===(int)$db->query('SELECT COUNT(DISTINCT loan_id) FROM loan_items WHERE returned_at IS NULL')->fetchColumn(),'Dashboard counts distinct open loan headers');
$assert((int)$summary['overdue_loan_count']===(int)$db->query('SELECT COUNT(DISTINCT loan_id) FROM loan_items WHERE returned_at IS NULL AND due_date<CURRENT_DATE')->fetchColumn(),'Dashboard counts distinct overdue headers');
$report=(new \Library\Repositories\ReportRepository($db))->rows('inventory');
$assert(count($report)===(int)$db->query('SELECT COUNT(*) FROM book_copies')->fetchColumn(),'Inventory report equals physical database rows');
$rollbackBook=$books->create(array_replace($data,['book_code'=>$tag.'-ROLLBACK','total_copies'=>2]));$rollbackCopies=$copies->all($rollbackBook);$good=(int)$rollbackCopies[0]['id'];$bad=(int)$rollbackCopies[1]['id'];
$db->exec('UPDATE book_copies SET status="lost",item_condition="lost" WHERE id='.$bad);
$before=(int)$db->query('SELECT COUNT(*) FROM loans WHERE reader_id='.$reader)->fetchColumn();
$reject(fn()=>$service->checkout($reader,[$good,$bad],$actor,date('Y-m-d'),date('Y-m-d',strtotime('+1 day'))),'Checkout with one unavailable copy rejected');
$assert(!$db->inTransaction() && (int)$db->query('SELECT COUNT(*) FROM loans WHERE reader_id='.$reader)->fetchColumn()===$before && $db->query('SELECT status FROM book_copies WHERE id='.$good)->fetchColumn()==='available','Failed transaction leaves no partial header or inventory update');
echo "Completion MySQL: $checks assertions passed.\n";
